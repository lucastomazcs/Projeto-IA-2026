const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const ids = ['product-form','preview-status','fill-example','help-dialog','help-open','help-close','reset','product','category','condition','cost','shipping','fees','margin'];
const elements = Object.fromEntries(ids.map(id=>[id,{value:'',textContent:'',events:{},addEventListener(name,fn){this.events[name]=fn;}}]));
let destination;
const context = {URL,document:{querySelector:selector=>elements[selector.slice(1)],getElementById:id=>elements[id]},window:{PRECIFICA_CONFIG:{streamlitUrl:'http://localhost:8501/'},location:{assign:url=>destination=url}}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../frontend/app.js'),'utf8'),context);
elements['fill-example'].events.click();
elements['product-form'].events.submit({preventDefault(){}});
const target = new URL(destination);
assert.equal(target.origin,'http://localhost:8501');
assert.equal(target.searchParams.get('product'),'JBL Tune 510BT');
assert.equal(target.searchParams.get('category'),'Fones de ouvido');
assert.equal(target.searchParams.get('cost'),'120');
assert.equal(target.searchParams.get('analisar'),'1');
destination=undefined;
elements.fees.value='90';
elements['product-form'].events.submit({preventDefault(){}});
assert.equal(destination,undefined);
assert.match(elements['preview-status'].textContent,/menos que 100%/);
console.log('Frontend -> Streamlit: OK (campos, URL e validação)');
